/* Build the cacheable browser index; integrity data stays in the five source manifests. */
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const packs=['natural','conversation','expanded','more','c1'];
const rows=[],seen=new Set();
const deep=process.argv.includes('--verify-audio');
const key=text=>text.normalize('NFC').replace(/\s+/gu,' ').trim().toLocaleLowerCase('pt-BR');
for (const [i,pack] of packs.entries()){
  const m=JSON.parse(fs.readFileSync('audio/'+pack+'-manifest.json','utf8'));
  assert.equal(m.meta.count,Object.keys(m.clips).length);
  for(const [k,c] of Object.entries(m.clips)){
    assert.equal(k,key(c.text));assert.ok(k.length>0&&k.length<3000&&!seen.has(k),'Missing/duplicate audio key');seen.add(k);
    const stem=createHash('sha256').update(c.text).digest('hex').slice(0,20);
    for(const [speed,p,h,t] of [['normal','src','sha256','duration'],['slow','slowSrc','slowSha256','slowDuration']]){
      const path='audio/'+pack+'-v1/'+stem+'-'+speed+'.mp3';
      assert.equal(c[p],path);assert.match(c[h],/^[a-f0-9]{64}$/);
      assert.ok(Number.isFinite(c[t])&&c[t]>0&&c[t]<=120);
      if(deep){assert.ok(fs.lstatSync(path).isFile());assert.equal(createHash('sha256').update(fs.readFileSync(path)).digest('hex'),c[h]);}
    }
    assert.notEqual(c.sha256,c.slowSha256);rows.push([k,i,stem,c.duration,c.slowDuration]);
  }
}
const out='/* Generated by tools/build_audio_catalog.mjs; do not edit. */\n(()=>{\n"use strict";\nconst packs='+JSON.stringify(packs)+';\nconst rows='+JSON.stringify(rows).replace(/</g,'\\u003c')+';\nconst clips=Object.create(null);\nfor(const [key,pack,stem,duration,slowDuration] of rows){const prefix="audio/"+packs[pack]+"-v1/"+stem;clips[key]={src:prefix+"-normal.mp3",slowSrc:prefix+"-slow.mp3",duration,slowDuration};}\nwindow.BORA_AUDIO={meta:{type:"neural-synthesis",language:"pt-BR",voice:"Kokoro pf_dora",humanRecording:false,count:rows.length,files:2*rows.length,normalRate:1,slowRate:.75},clips};\n})();\n';
const file='assets/audio-catalog.js';
if(process.argv.includes('--write'))fs.writeFileSync(file,out);
else assert.equal(fs.readFileSync(file,'utf8'),out,'Rebuild audio catalog with --write');
console.log(rows.length+' playback targets; '+(deep?2*rows.length+' MP3 digests verified; ':'')+Buffer.byteLength(out)+' runtime bytes.');
